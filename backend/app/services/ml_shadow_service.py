"""
ml_shadow_service.py
ProfitGuard AI — Phase 2: Shadow ML Inference & Serving Readiness Service.

GOVERNANCE & SAFETY SPECIFICATION:
1. SHADOW MODE ONLY:
   Predictions generated by this service are recorded purely as shadow audit metadata.
   They have ZERO authority over merchant actions and NEVER trigger automated cancellations.
2. SYNTHETIC PROVENANCE:
   The model is trained strictly on synthetic benchmark data (data/development/).
   All metadata explicitly labels data provenance as SYNTHETIC_DEVELOPMENT_ONLY.
3. FAIL-SAFE RESILIENCE:
   - INSUFFICIENT_DATA: Gracefully handled when order fields are absent.
   - RULE_BASED_FALLBACK: Gracefully returned if artifact is missing, corrupt, or incompatible.
   - Clean execution: Never raises unhandled exceptions to callers.
"""

